#!/usr/bin/env node
// Wraps graph.json and layout.json into data/board.js so the site also works from file://
// (fetch() of local JSON is blocked there). Run after build-graph / build-layout.
// Usage: node web/tools/bundle-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "data");
const graph = JSON.parse(readFileSync(join(dir, "graph.json"), "utf8"));
const layout = JSON.parse(readFileSync(join(dir, "layout.json"), "utf8"));
const body = JSON.stringify({ graph, layout: { width: layout.width, height: layout.height, positions: layout.positions, river: layout.river, geo: layout.geo } });
writeFileSync(join(dir, "board.js"), `// Generated by tools/bundle-data.mjs from graph.json and layout.json. Do not edit.\nwindow.FY_DATA=${body};\n`);
console.log(`wrote data/board.js (${body.length} bytes)`);
